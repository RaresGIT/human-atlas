import assert from 'node:assert/strict';
import {readRevision,saveRevision,parseRevision,recordMistake,REVISION_KEY} from '../app/study-revision.ts';
const valid=new Set(['a','b']);
let items=recordMistake([],'a');
items=recordMistake(items,'a');
items=recordMistake(items,'b');
assert.deepEqual(items,[{id:'a',mistakes:2},{id:'b',mistakes:1}]);
assert.deepEqual(parseRevision(null,valid).items,[]);
assert.ok(parseRevision('{oops',valid).warning);
assert.ok(parseRevision(JSON.stringify({version:99,items}),valid).warning);
const mixed={version:1,items:[...items,{id:'missing',mistakes:10},{id:'a',mistakes:1},{id:'b',mistakes:-1},{id:'a',mistakes:Infinity},{id:'b',mistakes:1.5},null]};
assert.deepEqual(parseRevision(JSON.stringify(mixed),valid).items,items);
assert.deepEqual(parseRevision(JSON.stringify({version:1,items:'bad'}),valid).items,[]);
assert.deepEqual(parseRevision(JSON.stringify({version:1,items:[{id:'a',mistakes:1e20}]}),valid).items,[]);
let raw=null;
const storage={getItem:key=>{assert.equal(key,REVISION_KEY);return raw;},setItem:(key,value)=>{assert.equal(key,REVISION_KEY);raw=value;}};
assert.equal(saveRevision(storage,items),'');
assert.deepEqual(readRevision(storage,valid).items,items);
assert.equal(saveRevision(storage,items.filter(i=>i.id!=='a')),'');
assert.deepEqual(readRevision(storage,valid).items,[{id:'b',mistakes:1}]);
const blocked={getItem:()=>{throw Error('blocked');},setItem:()=>{throw Error('full');}};
assert.ok(readRevision(blocked,valid).warning);
assert.ok(saveRevision(blocked,items));
console.log('Revision deduplication, validation, removal, persistence, and storage failure recovery passed.');
