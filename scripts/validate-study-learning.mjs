import assert from 'node:assert/strict';
import {classifyName,createQuiz,quizScene} from '../app/study-quiz.ts';
import {recordReview,dueRevision,parseRevision,mergeRevision,exportRevision} from '../app/study-revision.ts';
const concept={id:'a',name:'left clavicle',elements:['p1']},other={id:'b',name:'right clavicle',elements:['p2']};
assert.equal(classifyName(concept,'left collarbone'),'correct');
assert.equal(classifyName(concept,'right collarbone'),'wrong');
assert.equal(classifyName(concept,'clavicle'),'wrong');
assert.equal(classifyName(concept,'left clavicl'),'spelling');
assert.equal(classifyName(concept,'left scapula'),'wrong');
const quiz=createQuiz([concept,other],'context',()=>0,{limit:1,context:[concept,other]});
assert.equal(quiz.questions.length,1);
const scene=quizScene({reset:0,explode:1,selected:['p1'],focus:['p1'],visible:[],hidden:['p2'],labels:[concept],labelsVisible:true,isolate:true,view:'front',rotate:true},quiz,{parts:[],concepts:[concept,other]});
assert.deepEqual(new Set(scene.scope),new Set(['p1','p2']));
assert.deepEqual(scene.selected,[]);assert.equal(scene.focus,undefined);assert.equal(scene.explode,0);assert.equal(scene.labelsVisible,false);assert.equal(scene.hideNames,true);assert.equal(scene.inventoryGroups,undefined);
const day=86400000,now=10000;
let items=recordReview([],'a',true,now);
assert.equal(items[0].mistakes,0);assert.equal(items[0].attempts,1);assert.equal(items[0].dueAt,now+day);assert.equal(dueRevision(items,now).length,0);assert.equal(dueRevision(items,now+day).length,1);
items=recordReview(items,'a',true,now+day);assert.equal(items[0].dueAt,now+4*day);
items=recordReview(items,'a',false,now+4*day);assert.equal(items[0].streak,0);assert.equal(items[0].dueAt,now+4*day+600000);
const valid=new Set(['a','b']);
assert.deepEqual(parseRevision(exportRevision(items),valid).items,items);
const old=parseRevision(JSON.stringify({version:1,items:[{id:'b',mistakes:2}]}),valid).items;
assert.equal(dueRevision(old,now).length,1);assert.equal(recordReview(old,'b',true,now)[0].attempts,3);
assert.deepEqual(mergeRevision(items,'bad',valid).items,items);
assert.deepEqual(mergeRevision(items,exportRevision([{...items[0],lastReviewed:1}]),valid).items,items);
assert.equal(mergeRevision(items,exportRevision([{id:'unknown',mistakes:2}]),valid).items.length,1);
assert.equal(parseRevision(JSON.stringify({version:2,items:[{id:'b',mistakes:0,attempts:1,correct:2,streak:1,dueAt:0,lastReviewed:0}]}),valid).items.length,0);
assert.deepEqual(parseRevision(exportRevision([...items,{id:'a',mistakes:20}]),valid).items,items,'A legacy duplicate must not erase an existing review schedule');
assert.equal(parseRevision(exportRevision([{...items[0],dueAt:Number.MAX_SAFE_INTEGER}]),valid).items.length,0,'Safe integers beyond the JavaScript Date range are rejected');
assert.equal(parseRevision(exportRevision([{...items[0],lastReviewed:Number.MAX_SAFE_INTEGER}]),valid).items.length,0);
assert.equal(classifyName({name:'fibula'},'tibia'),'wrong');
console.log('Learning aliases, typo retries, context concealment, session limits, schedules and revision migration/import passed.');
